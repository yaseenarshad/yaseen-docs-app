#!/usr/bin/env node
/**
 * Vendors Material Icon Theme (YAZ-3440 D4, MIT) into the app: every icon of a release to
 * `client/public/material-icons/` (served beside the renderer bundle as `/material-icons/<file>`, so a row
 * loads only the icons it shows, and the icon picker loads the rest when it opens), its LICENSE, and the
 * release's own matching tables to `client/src/sidebar/materialIconData.ts`, which `materialIcons.ts` reads.
 *
 * The tables come from the release's generated manifest (`dist/material-icons.json`, what VS Code reads), not
 * from the repo's `src/core/icons/*.ts`: the open-folder icons and the clones exist only in a built release.
 *
 * Usage: node tools/materialIcons.mjs <unpacked npm package dir> [--commit <sha>]
 *   e.g. curl -sL https://registry.npmjs.org/material-icon-theme/-/material-icon-theme-5.40.0.tgz | tar xz -C /tmp/mit
 *        node tools/materialIcons.mjs /tmp/mit/package --commit "$(npm view material-icon-theme@5.40.0 gitHead)"
 *
 * The tarball's own package.json has no `gitHead` (the registry's metadata has it), so the release's commit comes
 * from `--commit`; without either the script stops, so the header never says "commit undefined" (YAZ-3470).
 */
import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const pkgDir = process.argv[2]
if (pkgDir === undefined) {
  console.error('Usage: node tools/materialIcons.mjs <unpacked material-icon-theme package dir>')
  process.exit(1)
}
const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'))
const commitAt = process.argv.indexOf('--commit')
const commit = commitAt === -1 ? pkg.gitHead : process.argv[commitAt + 1]
if (typeof commit !== 'string' || !/^[0-9a-f]{7,40}$/.test(commit)) {
  console.error(`No commit for material-icon-theme@${pkg.version}: pass --commit "$(npm view material-icon-theme@${pkg.version} gitHead)"`)
  process.exit(1)
}
const manifest = JSON.parse(readFileSync(join(pkgDir, 'dist/material-icons.json'), 'utf8'))

const out = join(repo, 'client/public/material-icons')
rmSync(out, { recursive: true, force: true })
mkdirSync(out, { recursive: true })
const ids = Object.keys(manifest.iconDefinitions).sort()
let bytes = 0
const clones = []
for (const id of ids) {
  const file = manifest.iconDefinitions[id].iconPath.split('/').pop()
  if (file !== `${id}.svg`) {
    if (file !== `${id}.clone.svg`) throw new Error(`unexpected icon file ${file} for ${id}`)
    clones.push(id)
  }
  copyFileSync(join(pkgDir, 'icons', file), join(out, file))
  bytes += readFileSync(join(out, file)).length
}
copyFileSync(join(pkgDir, 'LICENSE'), join(out, 'LICENSE'))
writeFileSync(
  join(out, 'README.md'),
  `Material Icon Theme ${pkg.version} (https://github.com/material-extensions/vscode-material-icon-theme, MIT, see LICENSE), commit ${commit}, from the npm release \`material-icon-theme@${pkg.version}\`. Written by \`tools/materialIcons.mjs\`; do not edit by hand.\n`,
)

/** `{ icon: [key, …] }` → `{ icon: 'key key …' }`: one string per icon keeps the module small. */
const byIcon = (table, keep = () => true) => {
  const grouped = {}
  for (const [key, icon] of Object.entries(table)) if (keep(key, table)) (grouped[icon] ??= []).push(key.toLowerCase())
  return Object.fromEntries(Object.entries(grouped).sort(([a], [b]) => a.localeCompare(b)).map(([icon, keys]) => [icon, [...new Set(keys)].sort().join(' ')]))
}
// Material writes each folder name five ways (`extendFolderNames`: name, .name, _name, -name, __name__); the
// lookup strips them again (`materialIcons.ts`), so only the plain name is kept here.
const VARIANT = /^(?:__(.+)__|[._-](.+))$/
const plain = (key, table) => {
  const m = VARIANT.exec(key)
  const base = m?.[1] ?? m?.[2]
  return base === undefined || table[base] !== table[key]
}
const data = {
  fileNames: byIcon(manifest.fileNames),
  fileExtensions: byIcon(manifest.fileExtensions),
  folderNames: byIcon(manifest.folderNames, plain),
}
const header = `/**
 * GENERATED by \`tools/materialIcons.mjs\` from Material Icon Theme ${pkg.version} (commit ${commit}, MIT): do not edit.
 * The release's own matching tables, each \`{ icon: 'key key …' }\` (lower case), and its icon ids. YAZ-3440 D4.
 */
`
writeFileSync(
  join(repo, 'client/src/sidebar/materialIconData.ts'),
  `${header}export const MATERIAL_VERSION = '${pkg.version}'
/** Every icon id, file name \`<id>.svg\` but the clones below. */
export const MATERIAL_IDS = '${ids.join(' ')}'
/** The ids whose file is \`<id>.clone.svg\`. */
export const MATERIAL_CLONES = '${clones.join(' ')}'
export const FILE_NAMES: Record<string, string> = ${JSON.stringify(data.fileNames, null, 0)}
export const FILE_EXTENSIONS: Record<string, string> = ${JSON.stringify(data.fileExtensions, null, 0)}
export const FOLDER_NAMES: Record<string, string> = ${JSON.stringify(data.folderNames, null, 0)}
`,
)
console.log(`${ids.length} icons, ${(bytes / 1024).toFixed(1)} KB, ${readdirSync(out).length} files in ${out}`)
