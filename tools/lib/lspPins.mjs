/**
 * THE LANGUAGE HELPERS' PINS (YAZ-3500; was `lspPack.mjs`, the pack-time staging of YAZ-3453 / YAZ-3455).
 *
 * The app ships no helper. The first switch-on of Settings › Code › "Jump across files" downloads them
 * (`desktop/src/main/lsp/download.ts`), and main takes the version, the tarball URL and the sha512 of each
 * one from `desktop/src/main/lsp/pins.ts` — never from the network. That file is made here, from the root
 * `package-lock.json`: the root `optionalDependencies` (`@typescript/typescript-<platform>-<arch>`, TypeScript 7)
 * and `devDependencies` (`pyright`) pin the same versions a dev build runs from `node_modules`.
 *
 * `node tools/lspPins.mjs` writes it; `--check` exits 1 when it differs. `tools/lspPins.test.mjs` fails
 * when the file and the lockfile disagree, so a version bump cannot ship old pins.
 */

/** The platforms the app ships (`<platform>-<arch>`, Node's names): each has a TypeScript 7 package. */
export const TYPESCRIPT_TARGETS = ['darwin-arm64', 'darwin-x64', 'win32-x64']
export const PYRIGHT_PACKAGE = 'pyright'
/** The one registry the app downloads from. */
export const REGISTRY = 'https://registry.npmjs.org/'

export function typescriptPackage(target) {
  return `@typescript/typescript-${target}`
}

/** The lockfile's record of `pkg`: `{ version, resolved, integrity }`. Throws when the lockfile lacks it. */
export function lockEntry(lock, pkg) {
  const entry = lock.packages?.[`node_modules/${pkg}`]
  if (!entry?.version || !entry.resolved || !entry.integrity) {
    throw new Error(`${pkg} is not in package-lock.json: add it to the root package.json (same version as the other helper packages) and run npm install`)
  }
  if (!entry.resolved.startsWith(REGISTRY)) throw new Error(`${pkg}: the lockfile's tarball ${entry.resolved} is not on ${REGISTRY}`)
  if (!/^sha512-[A-Za-z0-9+/]{86}==$/.test(entry.integrity)) throw new Error(`${pkg}: the lockfile's integrity is not one sha512`)
  return { version: entry.version, resolved: entry.resolved, integrity: entry.integrity }
}

/** The pins of every helper, from the lockfile. */
export function lspPins(lock) {
  const pin = (pkg) => {
    const { version, resolved, integrity } = lockEntry(lock, pkg)
    return { package: pkg, version, url: resolved, integrity }
  }
  const typescript = Object.fromEntries(TYPESCRIPT_TARGETS.map((target) => [target, pin(typescriptPackage(target))]))
  const versions = new Set(Object.values(typescript).map((p) => p.version))
  if (versions.size !== 1) throw new Error(`the @typescript/typescript-* packages have different versions in package-lock.json: ${[...versions].join(', ')}`)
  return { typescript, python: pin(PYRIGHT_PACKAGE) }
}

/** `desktop/src/main/lsp/pins.ts`, as text. */
export function pinsSource(lock) {
  const pins = lspPins(lock)
  const row = (p) => `{ package: '${p.package}', version: '${p.version}', url: '${p.url}', integrity: '${p.integrity}' }`
  return [
    '/**',
    ' * GENERATED by `node tools/lspPins.mjs` from package-lock.json. Do not edit: run it again after a helper',
    ' * version changes in the root package.json (`tools/lspPins.test.mjs` fails until then).',
    ' *',
    ' * The language helpers the app downloads on the first switch-on of "Jump across files" (YAZ-3500): the',
    ' * version, the npm registry tarball and its sha512 `integrity`. Main never looks a version up.',
    ' */',
    "import type { HelperPin } from './download'",
    '',
    '/** TypeScript 7, one package for each `<platform>-<arch>` the app ships. */',
    'export const TYPESCRIPT_PINS: Readonly<Record<string, HelperPin>> = {',
    ...Object.entries(pins.typescript).map(([target, p]) => `  '${target}': ${row(p)},`),
    '}',
    '',
    '/** pyright: one Node program for every platform, run on Electron\'s own Node. */',
    `export const PYRIGHT_PIN: HelperPin = ${row(pins.python)}`,
    '',
  ].join('\n')
}
